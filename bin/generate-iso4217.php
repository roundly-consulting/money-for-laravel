<?php

declare(strict_types=1);

/**
 * Regenerates resources/data/iso4217.php from the SIX ISO 4217 "List One" XML.
 *
 *   php bin/generate-iso4217.php [path-or-url-to-list-one.xml]
 *
 * Dev-only (needs ext-intl for the CLDR `en` symbols; not autoloaded, not shipped). Rows
 * whose minor unit is "N.A." (precious metals, SDR, test/no-currency codes) are excluded;
 * rows are deduplicated by code and sorted.
 */
$source = $argv[1] ?? 'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';

$xml = file_get_contents($source);

if ($xml === false || str_contains($xml, '<!DOCTYPE')) {
    fwrite(STDERR, "Cannot read a usable List One document from {$source}\n");
    exit(1);
}

$document = simplexml_load_string($xml, options: LIBXML_NONET);

if ($document === false) {
    fwrite(STDERR, "The List One document is not valid XML\n");
    exit(1);
}

$published = (string) $document['Pblshd'];
$currencies = ResourceBundle::create('en', 'ICUDATA-curr');
$cldr = (string) ResourceBundle::create('root', 'ICUDATA')?->get('Version');

$rows = [];

foreach ($document->CcyTbl->CcyNtry as $entry) {
    $code = trim((string) $entry->Ccy);
    $exponent = trim((string) $entry->CcyMnrUnts);

    if ($code === '' || ! ctype_digit($exponent) || isset($rows[$code])) {
        continue;
    }

    $symbol = null;
    $cldrEntry = $currencies?->get('Currencies')?->get($code);

    if ($cldrEntry instanceof ResourceBundle) {
        $candidate = (string) $cldrEntry->get(0);
        $symbol = $candidate === $code ? null : $candidate;
    }

    $rows[$code] = [$code, (int) $entry->CcyNbr, (int) $exponent, trim((string) $entry->CcyNm), $symbol];
}

ksort($rows);

$body = implode(",\n", array_map(
    static fn (array $row): string => sprintf(
        '    [%s, %d, %d, %s, %s]',
        var_export($row[0], true),
        $row[1],
        $row[2],
        var_export($row[3], true),
        $row[4] === null ? 'null' : var_export($row[4], true),
    ),
    array_values($rows),
));

$count = count($rows);

$php = <<<PHP
<?php

declare(strict_types=1);

/*
 * ISO 4217 active currencies with a defined minor unit — generated by bin/generate-iso4217.php.
 *
 * Source:  SIX ISO 4217 List One, published {$published}
 * Symbols: CLDR {$cldr} `en` standard symbols (null where CLDR `en` renders the code)
 * Rows:    {$count} — [code, numeric, exponent, name, symbol]
 *
 * Do not edit by hand: regenerate, then update the pinned row count in IsoDataTest.
 */

return [
{$body},
];

PHP;

file_put_contents(__DIR__.'/../resources/data/iso4217.php', $php);

fwrite(STDOUT, "Wrote {$count} currencies (List One {$published}, CLDR {$cldr}).\n");
